export function ensureWorkspaceFilesSeeded(
  baseWorkspacesDir: string
): Record<WorkspaceId, WorkspaceSeedBundle> {
  const cardsByWs: Record<WorkspaceId, WikiCard[]> = {
    'd2-studio': D2_CARDS,
    'sartoria-image': SARTORIA_CARDS,
    'apex-trade': APEX_CARDS,
  };
  const briefsByWs = buildBriefsWithRealMedia();
  const draftsByWs = createInitialDrafts();
  const extraByWs = buildVaultAndAnalytics();

  for (const wsId of Object.keys(WORKSPACE_PROFILES) as WorkspaceId[]) {
    const wikiDir = path.join(baseWorkspacesDir, wsId, 'wiki');
    fs.mkdirSync(wikiDir, { recursive: true });

    for (const card of cardsByWs[wsId]) {
      const filePath = path.join(wikiDir, `${card.slug}.md`);
      if (!fs.existsSync(filePath)) {
        const md = [
          '---',
          `title: ${JSON.stringify(card.title)}`,
          `category: ${card.category}`,
          `summary: ${JSON.stringify(card.summary)}`,
          `tags: ${JSON.stringify(card.tags)}`,
          `links: ${JSON.stringify(card.links)}`,
          `updatedAt: ${JSON.stringify(card.updatedAt)}`,
          `sourceType: ${JSON.stringify(card.sourceType || 'manual')}`,
          '---',
          '',
          card.content.trim(),
          '',
        ].join('\n');
        fs.writeFileSync(filePath, md, 'utf-8');
      }
    }
  }

  return {
    'd2-studio': {
      cards: D2_CARDS,
      briefs: briefsByWs['d2-studio'],
      drafts: draftsByWs['d2-studio'],
      ...extraByWs['d2-studio'],
    },
    'sartoria-image': {
      cards: SARTORIA_CARDS,
      briefs: briefsByWs['sartoria-image'],
      drafts: draftsByWs['sartoria-image'],
      ...extraByWs['sartoria-image'],
    },
    'apex-trade': {
      cards: APEX_CARDS,
      briefs: briefsByWs['apex-trade'],
      drafts: draftsByWs['apex-trade'],
      ...extraByWs['apex-trade'],
    },
  };
}
